"""Generate JSON Schema and TypeScript from the Pydantic contracts.

    python -m shared.export            # write shared/generated/**
    python -m shared.export --check    # exit 1 if committed output is stale (CI)

Outputs (committed, never hand-edited):
  generated/jsonschema/<Model>.json          validation-mode schema per model (LLM outputs, inbound)
  generated/contracts.schema.json            serialization-mode bundle of every model
  generated/ts/contracts.ts                  TypeScript types for frontend/ (serialization mode)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from pydantic.json_schema import models_json_schema

from shared import SCHEMA_VERSION
from shared.registry import MODELS

GENERATED = Path(__file__).resolve().parent.parent / "generated"
HEADER = (
    "// GENERATED by `python -m shared.export` from shared/ Pydantic models.\n"
    f"// Contract schema version {SCHEMA_VERSION}. DO NOT EDIT BY HAND.\n\n"
)


def _dump(obj: Any) -> str:
    return json.dumps(obj, indent=2, sort_keys=True) + "\n"


def bundle(mode: str) -> dict[str, Any]:
    _, schema = models_json_schema(
        [(m, mode) for m in MODELS],  # type: ignore[misc]
        ref_template="#/$defs/{model}",
        title="HackATL platform contracts",
    )
    schema["$schema"] = "https://json-schema.org/draft/2020-12/schema"
    schema["x-schema-version"] = SCHEMA_VERSION
    return schema


# ---------------------------------------------------------------- TypeScript


def _ts_type(s: dict[str, Any]) -> str:
    if "$ref" in s:
        return s["$ref"].rsplit("/", 1)[-1]
    if "const" in s:
        return json.dumps(s["const"])
    if "enum" in s:
        return " | ".join(json.dumps(v) for v in s["enum"])
    for key in ("anyOf", "oneOf"):
        if key in s:
            parts = []
            for sub in s[key]:
                t = _ts_type(sub)
                if t not in parts:
                    parts.append(t)
            return " | ".join(parts)
    if "allOf" in s and len(s["allOf"]) == 1:
        return _ts_type(s["allOf"][0])
    kind = s.get("type")
    if isinstance(kind, list):
        return " | ".join(_ts_type({**s, "type": x}) for x in kind)
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    if kind == "array":
        if "prefixItems" in s:
            return "[" + ", ".join(_ts_type(x) for x in s["prefixItems"]) + "]"
        inner = _ts_type(s.get("items", {}))
        return f"Array<{inner}>"
    if kind == "object":
        if s.get("properties"):
            return _ts_object(s, indent="  ")
        ap = s.get("additionalProperties")
        if isinstance(ap, dict) and ap:
            return f"Record<string, {_ts_type(ap)}>"
        return "Record<string, unknown>"
    return "unknown"


def _ts_object(s: dict[str, Any], indent: str = "") -> str:
    required = set(s.get("required", []))
    lines = ["{"]
    for name, prop in s.get("properties", {}).items():
        doc = prop.get("description")
        if doc:
            lines.append(f"{indent}  /** {doc.replace('*/', '* /')} */")
        opt = "" if name in required else "?"
        lines.append(f"{indent}  {name}{opt}: {_ts_type(prop)};")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def typescript(schema: dict[str, Any]) -> str:
    out = [HEADER, f'export const CONTRACT_SCHEMA_VERSION = "{SCHEMA_VERSION}";\n']
    for name in sorted(schema["$defs"]):
        d = schema["$defs"][name]
        if d.get("description"):
            out.append(
                "/** "
                + d["description"].strip().replace("*/", "* /").replace("\n", "\n * ")
                + " */"
            )
        if d.get("type") == "object" and "properties" in d:
            out.append(f"export interface {name} {_ts_object(d)}\n")
        else:
            out.append(f"export type {name} = {_ts_type(d)};\n")
    return "\n".join(out)


def render() -> dict[Path, str]:
    files: dict[Path, str] = {}
    for model in MODELS:
        files[GENERATED / "jsonschema" / f"{model.__name__}.json"] = _dump(
            model.model_json_schema(mode="validation")
        )
    ser = bundle("serialization")
    files[GENERATED / "contracts.schema.json"] = _dump(ser)
    files[GENERATED / "ts" / "contracts.ts"] = typescript(ser)
    return files


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args(argv)
    files = render()
    stale = []
    for path, content in files.items():
        current = path.read_text() if path.exists() else None
        if current != content:
            stale.append(path)
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(content)
    expected = set(files)
    for extra in (
        (GENERATED / "jsonschema").glob("*.json") if (GENERATED / "jsonschema").exists() else []
    ):
        if extra not in expected:
            stale.append(extra)
            if not args.check:
                extra.unlink()
    if args.check and stale:
        print("stale generated contracts:", *[str(s) for s in stale], sep="\n  ", file=sys.stderr)
        return 1
    print(f"{'checked' if args.check else 'wrote'} {len(files)} files ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
